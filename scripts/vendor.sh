#!/usr/bin/env bash
# Vendor the web adapter contract from an upstream Wealthfolio release tag.
#
#   scripts/vendor.sh v3.10.0
#
# Copies the upstream files unchanged into vendor/upstream/<tag>/, removes the
# previously vendored tag, and rewrites UPSTREAM_TAG and src/contract.ts.
# Needs `pnpm install` first (payload extraction uses typescript).
# Set UPSTREAM_REPO to fetch from another remote (default: upstream GitHub).
set -euo pipefail

TAG="${1:?usage: scripts/vendor.sh <tag>}"
REPO="${UPSTREAM_REPO:-https://github.com/wealthfolio/wealthfolio}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_DIR="apps/frontend/src/adapters"
# Upstream files copied verbatim. Paths are relative to $SRC_DIR.
FILES=("web/core.ts" "invoke-timeout.ts")
# The only imports core.ts may have. A new import needs a new shim.
EXPECTED_IMPORTS='"@/features/profiles/session"
"@/lib/auth-token"
"../invoke-timeout"
"../types"'

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git -C "$WORK" init -q
git -C "$WORK" remote add origin "$REPO"
git -C "$WORK" config core.sparseCheckout true
echo "$SRC_DIR/" >"$WORK/.git/info/sparse-checkout"
git -C "$WORK" fetch -q --depth=1 origin "refs/tags/$TAG:refs/tags/$TAG"
git -C "$WORK" checkout -q "tags/$TAG"
COMMIT="$(git -C "$WORK" rev-parse HEAD)"

actual_imports="$(grep -oE '^import .* from "[^"]+"' "$WORK/$SRC_DIR/web/core.ts" | grep -oE '"[^"]+"$' | sort)"
if [ "$actual_imports" != "$(echo "$EXPECTED_IMPORTS" | sort)" ]; then
  echo "core.ts imports changed at $TAG. Add shims, then update EXPECTED_IMPORTS." >&2
  echo "Expected:" >&2
  echo "$EXPECTED_IMPORTS" | sort >&2
  echo "Actual:" >&2
  echo "$actual_imports" >&2
  exit 1
fi

DEST="$ROOT/vendor/upstream/$TAG"
rm -rf "$ROOT/vendor/upstream"
mkdir -p "$DEST/adapters"
for f in "${FILES[@]}"; do
  mkdir -p "$(dirname "$DEST/adapters/$f")"
  cp "$WORK/$SRC_DIR/$f" "$DEST/adapters/$f"
done

# core.ts uses only the Logger type from ../types. Upstream types.ts pulls in
# the whole frontend type graph, so this one file is generated, not copied.
cat >"$DEST/adapters/types.ts" <<TS
// GENERATED by scripts/vendor.sh. Not an upstream file.
export type { Logger } from "../../../../src/shims/types";
TS

{
  echo "{"
  echo "  \"repo\": \"$REPO\","
  echo "  \"tag\": \"$TAG\","
  echo "  \"commit\": \"$COMMIT\","
  echo "  \"files\": {"
  n=${#FILES[@]}
  i=0
  for f in "${FILES[@]}"; do
    i=$((i + 1))
    sum="$(sha256sum "$DEST/adapters/$f" | cut -d' ' -f1)"
    sep=","
    [ "$i" -eq "$n" ] && sep=""
    echo "    \"$SRC_DIR/$f\": \"$sum\"$sep"
  done
  echo "  }"
  echo "}"
} >"$DEST/SOURCE.json"

node "$ROOT/scripts/extract-payloads.mjs" "$DEST/adapters/web/core.ts" "$DEST/payloads.json"

echo "$TAG" >"$ROOT/UPSTREAM_TAG"
cat >"$ROOT/src/contract.ts" <<TS
// GENERATED by scripts/vendor.sh. Points the CLI at the vendored upstream contract.
export * from "../vendor/upstream/$TAG/adapters/web/core";
export { default as PAYLOADS } from "../vendor/upstream/$TAG/payloads.json";
export const UPSTREAM_TAG = "$TAG";
TS

echo "Vendored $TAG ($COMMIT) into vendor/upstream/$TAG"
